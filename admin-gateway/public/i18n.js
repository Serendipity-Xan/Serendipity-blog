export function getLang() {
    try {
        return localStorage.getItem(LANG_STORAGE_KEY) === 'en' ? 'en' : 'zh-CN';
    } catch {
        return 'zh-CN';
    }
}

export function setLang(lang) {
    const next = lang === 'en' ? 'en' : 'zh-CN';
    try {
        localStorage.setItem(LANG_STORAGE_KEY, next);
    } catch {}
    document.documentElement.lang = next;
    return next;
}

export function t(zhText, enText) {
    return getLang() === 'en' ? enText : zhText;
}

export function translateText(raw) {
    if (getLang() !== 'en' || !raw || typeof raw !== 'string') return raw;
    const trimmed = raw.trim();
    if (!trimmed) return raw;

    let translated = EXACT_MAP[trimmed];
    if (!translated) {
        for (const [regex, fn] of PATTERN_RULES) {
            const m = trimmed.match(regex);
            if (m) {
                translated = fn(...m);
                break;
            }
        }
    }
    if (!translated) return raw;
    const lead = raw.slice(0, raw.indexOf(trimmed));
    const tail = raw.slice(raw.indexOf(trimmed) + trimmed.length);
    return `${lead}${translated}${tail}`;
}

// Store original Chinese strings so toggling back EN -> zh-CN restores cleanly
const origTextMap = new WeakMap();
const origAttrMap = new WeakMap();
const TRANSLATABLE_ATTRS = ['placeholder', 'title', 'aria-label'];
const SKIP_USER_DATA_SELECTOR = 'code, pre, [data-no-i18n], .tag-checkbox-pill span, .md-preview';

function rememberAndApplyTextNode(node, lang) {
    const parent = node.parentElement;
    if (!parent || parent.closest(SKIP_USER_DATA_SELECTOR)) return;
    if (parent.tagName === 'TEXTAREA' || parent.tagName === 'SCRIPT' || parent.tagName === 'STYLE') return;
    // Skip user-created post/page/tag/friend titles inside table links
    if (parent.tagName === 'A' && parent.closest('tbody td:first-child')) return;

    if (!origTextMap.has(node)) {
        origTextMap.set(node, node.nodeValue);
    }
    const orig = origTextMap.get(node);
    const next = lang === 'en' ? translateText(orig) : orig;
    if (node.nodeValue !== next) {
        node.nodeValue = next;
    }
}

function rememberAndApplyAttrs(el, lang) {
    if (el.closest?.(SKIP_USER_DATA_SELECTOR)) return;
    let saved = origAttrMap.get(el);
    if (!saved) {
        saved = {};
        for (const attr of TRANSLATABLE_ATTRS) {
            if (el.hasAttribute(attr)) {
                saved[attr] = el.getAttribute(attr);
            }
        }
        origAttrMap.set(el, saved);
    }
    for (const [attr, orig] of Object.entries(saved)) {
        const next = lang === 'en' ? translateText(orig) : orig;
        if (el.getAttribute(attr) !== next) {
            el.setAttribute(attr, next);
        }
    }
}

let isApplying = false;

export function applyI18nToSubtree(root = document.body) {
    if (!root || isApplying) return;
    const lang = getLang();
    isApplying = true;
    try {
        if (root.nodeType === Node.ELEMENT_NODE) {
            rememberAndApplyAttrs(root, lang);
        }
        const walker = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
        let cur = walker.nextNode();
        while (cur) {
            if (cur.nodeType === Node.TEXT_NODE) {
                rememberAndApplyTextNode(cur, lang);
            } else if (cur.nodeType === Node.ELEMENT_NODE) {
                rememberAndApplyAttrs(cur, lang);
            }
            cur = walker.nextNode();
        }
    } finally {
        isApplying = false;
    }
}

let observerStarted = false;

export function startI18nObserver() {
    if (observerStarted) return;
    observerStarted = true;
    document.documentElement.lang = getLang();
    applyI18nToSubtree(document.body);

    const observer = new MutationObserver((mutations) => {
        if (isApplying || getLang() !== 'en') return;
        for (const mut of mutations) {
            if (mut.type === 'characterData') {
                isApplying = true;
                try {
                    rememberAndApplyTextNode(mut.target, 'en');
                } finally {
                    isApplying = false;
                }
            } else if (mut.type === 'childList') {
                for (const node of mut.addedNodes) {
                    if (node.nodeType === Node.TEXT_NODE) {
                        isApplying = true;
                        try {
                            rememberAndApplyTextNode(node, 'en');
                        } finally {
                            isApplying = false;
                        }
                    } else if (node.nodeType === Node.ELEMENT_NODE) {
                        applyI18nToSubtree(node);
                    }
                }
            }
        }
    });

    observer.observe(document.body, {
        childList: true,
        subtree: true,
        characterData: true
    });
}
